def verify_environmental(n, seed, participants):
    env = load_manifest_tsv(ENV_MANIFEST)
    sampled = sample_participants(n, seed, participants)
    checked, matched, nox_skipped_events = 0, 0, 0

    for tei, pid in sampled:
        rows = env.get(pid, [{}])
        fp_suffix = rows[0].get("env_sensor_filepath")
        if not fp_suffix or fp_suffix == "None":
            continue
        try:
            source_rows = read_env_csv(full_path(fp_suffix))
        except Exception:
            continue

        for column, stage_uid in ENV_COLUMN_TO_STAGE.items():
            try:
                source_hourly = aggregate_env_column(source_rows, column)
            except Exception:
                continue
            events = get_all_events(tei, stage_uid)
            for event in events:
                occurred = event.get("occurredAt")
                if not occurred:
                    continue
                key = hour_key(occurred)
                src_match = next((v for k, v in source_hourly.items() if hour_key(k) == key), None)
                if src_match is None:
                    continue
                field_map = dict(ENV_FIELD_MAP)
                if column == "hum":
                    field_map.update(ENV_HUMIDITY_EXTRA_MAP)
                for field, de_uid in field_map.items():
                    dhis2_val = event_data_value(event, de_uid)
                    checked += 1
                    if close_enough(dhis2_val, src_match.get(field)):
                        matched += 1
            time.sleep(0.03)

        # NOx: count how many events exist but are NOT verified, so
        # this is visible in the final report rather than silently absent.
        nox_events = get_all_events(tei, M.ENVIRONMENTAL_STAGES["nox"][0])
        nox_skipped_events += len(nox_events)

    return {"checked": checked, "matched": matched,
            "nox_events_not_verified": nox_skipped_events}


def verify_diagnosis(n, seed, participants):
    import pandas as pd
    cond = pd.read_csv(CONDITION_OCCURRENCE_CSV)
    cond["person_id"] = cond["person_id"].astype(str)

    sampled = sample_participants(n, seed, participants)
    checked, matched = 0, 0

    for tei, pid in sampled:
        source_rows = cond[cond["person_id"] == str(pid)]
        events = get_all_events(tei, M.DIAGNOSIS_STAGE_UID)
        for event in events:
            dhis2_code = event_data_value(event, M.DIAGNOSIS_FIELDS["condition_code"])
            dhis2_label = event_data_value(event, M.DIAGNOSIS_FIELDS["condition_label"])
            dhis2_date = event_data_value(event, M.DIAGNOSIS_FIELDS["diagnosis_date"])

            src_match = None
            for _, srow in source_rows.iterrows():
                raw = str(srow.get("condition_source_value", ""))
                if "," in raw:
                    src_code, src_label = raw.split(",", 1)
                    src_code, src_label = src_code.strip(), src_label.strip()
                else:
                    src_code, src_label = raw.strip(), ""
                if src_code == dhis2_code:
                    src_match = (src_code, src_label, str(srow.get("condition_start_date", "")))
                    break
            if src_match is None:
                continue
            src_code, src_label, src_date = src_match
            checked += 3
            if close_enough(dhis2_code, src_code):
                matched += 1
            if close_enough(dhis2_label, src_label):
                matched += 1
            if close_enough(dhis2_date, src_date):
                matched += 1
        time.sleep(0.03)

    return {"checked": checked, "matched": matched}


def verify_retinal_photography(n, seed, participants):
    manifest = load_manifest_tsv(RETINAL_PHOTOGRAPHY_MANIFEST)
    sampled = sample_participants(n, seed, participants)
    checked, matched = 0, 0

    for tei, pid in sampled:
        rows = manifest.get(pid, [])
        if not rows:
            continue
        events = get_all_events(tei, M.RETINAL_PHOTOGRAPHY_STAGE_UID)
        by_sop = {}
        for event in events:
            sop = event_data_value(event, RETINAL_PHOTOGRAPHY_FIELD_MAP["sop_instance_uid"])
            if sop:
                by_sop[sop] = event
        for row in rows:
            sop = row.get("sop_instance_uid")
            event = by_sop.get(sop)
            if not event:
                continue
            for field, de_uid in RETINAL_PHOTOGRAPHY_FIELD_MAP.items():
                if field == "sop_instance_uid":
                    continue  # already used as the join key
                dhis2_val = event_data_value(event, de_uid)
                checked += 1
                if close_enough(dhis2_val, row.get(field)):
                    matched += 1
        time.sleep(0.03)

    return {"checked": checked, "matched": matched}


def verify_count_reconciliation(stage_uid, manifest_path, n, seed, participants):
    """Fallback for OCTA and ECG: event-count reconciliation only, not
    a full field diff, consistent with how completeness was already
    established for these domains in Phase 24-26."""
    manifest = load_manifest_tsv(manifest_path)
    sampled = sample_participants(n, seed, participants)
    checked, matched = 0, 0

    for tei, pid in sampled:
        expected = len(manifest.get(pid, []))
        events = get_all_events(tei, stage_uid, fields="event")
        checked += 1
        if len(events) == expected:
            matched += 1
        time.sleep(0.03)

    return {"checked": checked, "matched": matched}


