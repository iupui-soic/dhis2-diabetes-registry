def get_all_participants_with_person_id():
    out, page = [], 1
    while True:
        r = SESSION.get(
            f"{BASE_URL}/api/tracker/trackedEntities",
            params={"program": M.PROGRAM_UID, "fields": "trackedEntity,attributes",
                    "page": page, "pageSize": PAGE_SIZE},
            timeout=30,
        )
        r.raise_for_status()
        batch = r.json().get("trackedEntities", [])
        if not batch:
            break
        for t in batch:
            person_id = next((a.get("value") for a in t.get("attributes", [])
                               if a.get("attribute") == M.PERSON_ID_ATTR_UID), None)
            out.append((t["trackedEntity"], person_id))
        page += 1
    return out


def get_all_events(tracked_entity_uid, stage_uid, fields="*"):
    all_events, page = [], 1
    while True:
        r = SESSION.get(
            f"{BASE_URL}/api/tracker/events",
            params={"program": M.PROGRAM_UID, "programStage": stage_uid,
                    "trackedEntity": tracked_entity_uid, "fields": fields,
                    "page": page, "pageSize": PAGE_SIZE},
            timeout=30,
        )
        r.raise_for_status()
        batch = r.json().get("events", [])
        if not batch:
            break
        all_events.extend(batch)
        if len(batch) < PAGE_SIZE:
            break
        page += 1
    return all_events


def event_data_value(event, de_uid):
    for dv in event.get("dataValues", []):
        if dv.get("dataElement") == de_uid:
            return dv.get("value")
    return None


COUNT_CACHE_FILE = "stage_count_cache.json"


def _load_count_cache():
    if os.path.exists(COUNT_CACHE_FILE):
        with open(COUNT_CACHE_FILE) as f:
            return json.load(f)
    return {}


def _save_count_cache(cache):
    with open(COUNT_CACHE_FILE, "w") as f:
        json.dump(cache, f, indent=2)


def get_stage_event_count(stage_uid, max_retries=4):
    """totalPages=true forces DHIS2 to run a full server-side count,
    which can be slow on large stages — a plain 30s timeout isn't
    always enough. Retries with backoff and a longer timeout, and
    caches results locally so a late-stage failure doesn't throw away
    counts already obtained for other stages."""
    cache = _load_count_cache()
    if stage_uid in cache:
        return cache[stage_uid]

    last_error = None
    for attempt in range(1, max_retries + 1):
        try:
            r = SESSION.get(
                f"{BASE_URL}/api/tracker/events",
                params={"program": M.PROGRAM_UID, "programStage": stage_uid,
                        "pageSize": 1, "totalPages": "true"},
                timeout=180,
            )
            r.raise_for_status()
            total = r.json().get("page", {}).get("total", 0)
            cache[stage_uid] = total
            _save_count_cache(cache)
            return total
        except requests.exceptions.RequestException as e:
            last_error = e
            wait = 5 * attempt
            print(f"    [retry {attempt}/{max_retries}] {stage_uid} count timed out, "
                  f"waiting {wait}s before retrying...")
            time.sleep(wait)

    print(f"    [WARN] {stage_uid} count failed after {max_retries} attempts "
          f"({last_error}). Using 0 — this will under-weight this group's "
          f"sample size; rerun later to fix if needed.")
    return 0


