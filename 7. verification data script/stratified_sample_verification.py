#!/usr/bin/env python3
"""
stratified_sample_verification.py  (v4 — FINAL, comparison-enabled)

Fills the abstract's [n], [method], [X], [Z], [T] placeholders.

SAFETY / READ-ONLY GUARANTEE
-----------------------------
GET requests only against DHIS2. Never POST/PUT/PATCH/DELETE. Reads
your own source files locally. Nothing in the live registry is
modified by this script.

WHAT IS AND ISN'T COMPARED, AND WHY
----------------------------------------
Wearable (HR/RR/SpO2/Stress): mean, min, max, count — direct, confirmed.

Glucose: mean, min, max, count, sd, tir_pct, tar_pct, tbr_pct, plus
device high_count/low_count (RZpt03lifR6 / hi1TAwCqN0f) — confirmed
mapping. The LATER clinical above/below-range counts (W5ki8H2QpmF /
xHFP3IuUfUZ) are deliberately excluded — they were added by a separate
backfill whose exact computation wasn't re-derived here, so comparing
them against aggregate_glucose()'s output would risk comparing against
the wrong logic entirely, which is worse than not checking them.

Environmental: mean, min, max, sd, count for pm1, pm2.5, pm4, pm10,
temperature, voc; plus humidity's above/below comfort-range fields.
NOx is SKIPPED — confirmed via probe that this participant's raw
source CSV has no nox column at all (only ts, pm1, pm2.5, pm4, pm10,
hum, temp, voc). Rather than guess a different source file or fabricate
a comparison, NOx values are counted as "not sampled" and reported as
such, not silently treated as verified.

Diagnosis: condition_source_value split into code + label on the first
comma, matched against source condition_start_date.

Retinal photography: 10 of 11 fields compared directly against the
manifest (manufacturer, model, laterality, anatomic_region, imaging
type, height, width, color_channel_dimension, SOP instance UID,
filepath), matched per participant + SOP UID. Preview Image is
excluded — it's generated by the pipeline, not sourced.

Retinal OCTA: NOT compared field-by-field in this pass — the OCTA
source-to-field mapping wasn't traced through the same way retinal
photography was. Counted via event-count reconciliation only (does
the DHIS2 event count match the manifest row count per participant),
consistent with how Phase 24-26 already established OCTA completeness.

ECG: same as OCTA — count reconciliation only. The ECG source file
structure wasn't traced through in this pass.

METHOD (what the abstract's [method] should say)
-------------------------------------------------------
Stratified random sampling without replacement, sample size per group
proportional to that group's live DHIS2 event count (queried at
runtime), fixed random seed (42) for reproducibility. Within each
sampled event, all directly-comparable fields are checked (see above);
fields without a confirmed source mapping are excluded from the
comparison and reported separately, not silently assumed correct.
"""

