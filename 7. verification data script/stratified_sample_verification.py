def sample_participants(n, seed, participants):
    rng = random.Random(seed)
    valid = [(tei, pid) for tei, pid in participants if pid]
    return rng.sample(valid, min(n, len(valid)))


def verify_wearable(n, seed, participants):
    wam = load_manifest_tsv(WAM_MANIFEST)
    sampled = sample_participants(n, seed, participants)
    checked, matched, skipped = 0, 0, 0

    for tei, pid in sampled:
        rows = wam.get(pid, [{}])
        row = rows[0]
        for name, (col, extractor, stage_uid, field_map) in CONTINUOUS_WEARABLE.items():
            fp_suffix = row.get(col)
            if not fp_suffix:
                continue
            try:
                source_hourly = aggregate_simple(extractor(full_path(fp_suffix)))
            except Exception:
                continue
            events = get_all_events(tei, stage_uid)
            for event in events:
                occurred = event.get("occurredAt")
                if not occurred:
                    continue
                key = hour_key(occurred)
                src_match = next((v for k, v in source_hourly.items() if hour_key(k) == key), None)
                if src_match is None:
                    continue
                for field, de_uid in field_map.items():
                    dhis2_val = event_data_value(event, de_uid)
                    checked += 1
                    if close_enough(dhis2_val, src_match.get(field)):
                        matched += 1
            time.sleep(0.03)

    return {"checked": checked, "matched": matched, "skipped": skipped}


