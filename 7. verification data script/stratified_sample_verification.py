def load_manifest_tsv(path, key="person_id"):
    with open(path) as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    out = {}
    for row in rows:
        out.setdefault(row[key], []).append(row)
    return out


def full_path(fp_suffix, root=AI_READI_FIXED_ROOT):
    return f"{root}{fp_suffix}" if fp_suffix.startswith("/") else f"{root}/{fp_suffix}"


def hour_key(value):
    """Normalizes an hour-bucket identifier (ISO string with tz/ms, or
    'YYYY-MM-DD HH:MM' space format) to a comparable (Y,M,D,H) tuple.
    No timezone conversion is applied — both sides are assumed to
    represent the same wall-clock hour, matching how they were
    originally written."""
    if isinstance(value, datetime):
        dt = value
    else:
        s = str(value).replace("Z", "").split("+")[0].strip()
        if "T" in s:
            dt = datetime.fromisoformat(s.split(".")[0])
        else:
            dt = datetime.strptime(s, "%Y-%m-%d %H:%M")
    return (dt.year, dt.month, dt.day, dt.hour)


