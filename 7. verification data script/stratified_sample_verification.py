def save_checkpoint(cp):
    with open(CHECKPOINT_FILE, "w") as f:
        json.dump(cp, f, indent=2)


def close_enough(a, b, tol=0.01):
    """Numeric-aware comparison: tries float compare with tolerance,
    falls back to exact string compare. Missing values on EITHER side
    are never a match — "both blank" is not "confirmed correct"."""
    if a is None or b is None:
        return False
    try:
        return abs(float(a) - float(b)) <= tol
    except (TypeError, ValueError):
        return str(a).strip() == str(b).strip()


